/**
 * Audit and repair initial Contract drafts left without legal lease dates
 * when targetMoveInDate was the Reservation's only move-in date.
 *
 * Dry run (default):
 *   node scripts/repair_contract_target_movein_drafts.mjs
 *
 * Apply only candidates classified safe by the same audit:
 *   node scripts/repair_contract_target_movein_drafts.mjs --write
 *
 * Optional narrow verification:
 *   --contract-number=LIL-GP-2026-00088
 */
import dotenv from "dotenv";
import mongoose from "mongoose";

dotenv.config();

const write = process.argv.includes("--write");
const contractNumberArg = process.argv.find((argument) =>
  argument.startsWith("--contract-number="));
const contractNumber = contractNumberArg?.slice("--contract-number=".length) || null;

const iso = (value) => value ? new Date(value).toISOString() : null;

if (!process.env.MONGODB_URI) {
  throw new Error("MONGODB_URI is required.");
}

await mongoose.connect(process.env.MONGODB_URI, { serverSelectionTimeoutMS: 10_000 });

try {
  const { Contract } = await import("../models/index.js");
  const {
    auditContractDraftDateRecovery,
    inspectContractDateRecovery,
    repairContractDraftDates,
  } = await import("../services/contractDraftRecoveryService.js");
  const { autoGenerateDepositSettledContract } = await import(
    "../services/autoContractOrchestratorService.js"
  );
  const { resolveTenantContractDocument } = await import(
    "../services/tenantContractDocumentResolver.js"
  );
  const { resolveTenantCanonicalContract } = await import(
    "../services/tenantContractSelectionService.js"
  );

  const audit = await auditContractDraftDateRecovery({ contractNumber });
  if (contractNumber) {
    const exact = await Contract.findOne({ contractNumber }).lean();
    if (exact) {
      const inspection = await inspectContractDateRecovery(exact._id);
      const canonical = await resolveTenantCanonicalContract(exact.tenantId, {
        includeEarlyStages: true,
      }).catch(() => null);
      const currentTenantDocument = resolveTenantContractDocument(canonical);
      console.log(JSON.stringify({
        explicitContractInspection: {
          contractNumber: inspection.contractNumber,
          tenant: inspection.tenant,
          reservation: inspection.reservation,
          branch: inspection.branch,
          currentStatus: inspection.currentStatus,
          currentLeaseStartDate: iso(inspection.currentLeaseStartDate),
          currentLeaseEndDate: iso(inspection.currentLeaseEndDate),
          resolvedMoveInDate: iso(inspection.resolvedMoveInDate),
          resolvedSourceField: inspection.resolvedSourceField,
          proposedLeaseStartDate: iso(inspection.proposedLeaseStartDate),
          proposedLeaseEndDate: iso(inspection.proposedLeaseEndDate),
          eligibleForDeterministicRepair: inspection.eligible ? "YES" : "NO",
          reason: inspection.reasons.join(" ") || "Record does not match the deterministic scan pattern.",
          beforeMissingFields: inspection.beforeValidation?.missingFields?.map(({ field }) => field) || [],
          mobileCurrentProjection: {
            contractFound: Boolean(canonical),
            contractIdMatches: String(canonical?._id || "") === String(exact._id),
            tenantDocumentAvailable: currentTenantDocument.available,
            tenantDocumentType: currentTenantDocument.type,
            sourceVersion: currentTenantDocument.version,
            publishedAt: iso(currentTenantDocument.publishedAt),
          },
        },
      }, null, 2));
    } else {
      console.log(JSON.stringify({ explicitContractInspection: { contractNumber, found: false } }, null, 2));
    }
  }
  console.log(JSON.stringify({
    mode: write ? "WRITE" : "DRY_RUN",
    database: mongoose.connection.name,
    totalScanned: audit.totalScanned,
    matchingCandidates: audit.matchingCandidates,
    safeDeterministicRepairs: audit.safeCandidates,
    ambiguousOrSkipped: audit.ambiguous,
    alreadyHealthy: audit.alreadyHealthy,
  }, null, 2));

  for (const candidate of audit.candidates) {
    console.log(JSON.stringify({
      contractNumber: candidate.contractNumber,
      tenant: candidate.tenant,
      reservation: candidate.reservation,
      reservationId: candidate.reservationId,
      branch: candidate.branch,
      currentStatus: candidate.currentStatus,
      currentLeaseStartDate: iso(candidate.currentLeaseStartDate),
      currentLeaseEndDate: iso(candidate.currentLeaseEndDate),
      resolvedMoveInDate: iso(candidate.resolvedMoveInDate),
      resolvedSourceField: candidate.resolvedSourceField,
      proposedLeaseStartDate: iso(candidate.proposedLeaseStartDate),
      proposedLeaseEndDate: iso(candidate.proposedLeaseEndDate),
      eligibleForDeterministicRepair: candidate.eligible ? "YES" : "NO",
      reason: candidate.eligible ? "Deterministic canonical repair" : candidate.reasons.join(" "),
      beforeMissingFields: candidate.beforeValidation?.missingFields?.map(({ field }) => field) || [],
      proposedMissingFields: candidate.proposedValidation?.missingFields?.map(({ field }) => field) || [],
      proposedValidationBlocker:
        candidate.proposedValidation?.missingFields?.[0]?.field ||
        candidate.proposedValidation?.errors?.[0]?.code ||
        candidate.proposedValidation?.conflicts?.[0]?.code ||
        candidate.proposedValidation?.warnings?.[0]?.code ||
        null,
    }, null, 2));
  }

  let mutations = 0;
  const repairResults = [];
  if (write) {
    for (const candidate of audit.candidates.filter(({ eligible }) => eligible)) {
      const source = await Contract.findById(candidate.contractId).lean();
      const actorId = source?.updatedBy || source?.createdBy || candidate.tenantId;
      const repair = await repairContractDraftDates({
        contractId: candidate.contractId,
        actorId,
      });
      mutations += repair.mutations;

      let lifecycle = null;
      if (repair.repaired) {
        lifecycle = await autoGenerateDepositSettledContract({
          reservationId: candidate.reservationId,
          actorId,
        });
      }
      const current = await Contract.findById(candidate.contractId).lean();
      const tenantDocument = resolveTenantContractDocument(current);
      repairResults.push({
        contractNumber: candidate.contractNumber,
        mutations: repair.mutations,
        lifecycle,
        leaseStartDate: iso(current?.leaseStartDate),
        leaseEndDate: iso(current?.leaseEndDate),
        oldStatus: candidate.currentStatus,
        newStatus: current?.status || null,
        tenantDocument: {
          available: tenantDocument.available,
          type: tenantDocument.type,
          sourceVersion: tenantDocument.version,
          documentUrl: tenantDocument.available
            ? `/api/m/contracts/${candidate.contractId}/documents/${tenantDocument.type === "generated_draft" ? "prepared" : "final"}`
            : null,
          publishedAt: iso(tenantDocument.publishedAt),
        },
      });
    }
  }

  console.log(JSON.stringify({
    mode: write ? "WRITE_RESULT" : "DRY_RUN_RESULT",
    mutations,
    repairResults,
  }, null, 2));
} finally {
  await mongoose.disconnect();
}
